def _sources(platform: str, base: Path) -> PlatformSources:
    """A machine of *platform* with no plist, no registry value: files only."""
    registry = (lambda hive, key, name: NOT_FOUND) if platform == "win32" else None
    return PlatformSources(platform, registry, base / "no-prefs", "someone")


def _norm(obj: object, base: Path) -> object:
    """Replace the temp dir with ``<TMP>`` and use ``/`` in every string.

    Works on decoded data, so Windows paths (backslashes, JSON-escaped) compare
    equal to the POSIX golden.
    """
    if isinstance(obj, str):
        return obj.replace(str(base), "<TMP>").replace("\\", "/")
    if isinstance(obj, list):
        return [_norm(v, base) for v in obj]
    if isinstance(obj, dict):
        return {k: _norm(v, base) for k, v in obj.items()}
    return obj


def _run(name: str, scenario: dict, base: Path, platform: str) -> list[dict]:
    managed = base / "managed"
    managed.mkdir(parents=True)
    if "settings" in scenario:
        (managed / "managed-settings.json").write_text(json.dumps(scenario["settings"]))
    if "settings_text" in scenario:
        (managed / "managed-settings.json").write_text(scenario["settings_text"])
    if "mcp" in scenario:
        (managed / "managed-mcp.json").write_text(json.dumps(scenario["mcp"]))
    for fname, doc in scenario.get("dropins", {}).items():
        d = managed / "managed-settings.d"
        d.mkdir(exist_ok=True)
        (d / fname).write_text(json.dumps(doc))
    configs: list[DiscoveredConfig] = []
    repo = base / "repo"
    if "project_allow" in scenario:
        path = repo / ".claude" / "settings.json"
        path.parent.mkdir(parents=True)
        raw = {"allowedMcpServers": scenario["project_allow"]}
        path.write_text(json.dumps(raw))
        configs.append(
            DiscoveredConfig(
                client_name="claude-code-project",
                root_key="mcpServers",
                path=path,
                raw=raw,
            )
        )
    errors: list[str] = []
    policy = read_effective_policy(managed, errors, _sources(platform, base))
    findings = analyze_managed_policy(policy, _servers(), configs, base / "h", repo)
    out = []
    for f in findings:
        data = json.loads(f.model_dump_json())
        # ``line`` (STORY-0141) postdates the golden; managed policy never sets it.
        assert data.pop("line", None) is None
        out.append(data)
    return _norm({"findings": out, "errors": errors}, base)  # type: ignore[return-value]


def _collect(tmp_path: Path, platform: str) -> dict:
    return {
        name: _run(name, sc, tmp_path / name, platform)
        for name, sc in sorted(_SCENARIOS.items())
    }


@pytest.mark.parametrize("platform", ["linux", "darwin", "win32"])
def test_file_only_output_is_byte_identical(tmp_path: Path, platform: str) -> None:
    """On every platform, with no plist and no registry value, the output is
    the pre-STORY-0144 output (same caveat text, no source named)."""
    got = _collect(tmp_path, platform)
    if os.environ.get("MCP_AUDIT_UPDATE_GOLDEN") and platform == "linux":
        GOLDEN.parent.mkdir(exist_ok=True)
        GOLDEN.write_text(json.dumps(got, indent=1, sort_keys=True) + "\n")
    want = json.loads(GOLDEN.read_text())
    assert json.dumps(got, sort_keys=True) == json.dumps(want, sort_keys=True)
    # The pin is only worth something if it covers every file-source rule.
    ids = {f["id"] for sc in got.values() for f in sc["findings"]}
    assert {"MANAGED-001", "MANAGED-002", "MANAGED-003", "MANAGED-004"} <= ids
    assert "MANAGED-005" in ids
